"""Stage 2 gate: check raw files against the manifest, expected volumes, and the second route.

Writes reports/stage2_acquisition.md. Exits non-zero if a hard check fails.
"""

import sys

import pandas as pd

from hothand.acquire import MANIFEST, count_csv_rows, sha256
from hothand.config import RAW, ROOT, load_config

REPORT = ROOT / "reports" / "stage2_acquisition.md"
KEY = ["GAME_ID", "GAME_EVENT_ID", "PLAYER_ID"]


def check_manifest(manifest: pd.DataFrame) -> pd.DataFrame:
    """Recount rows and rehash every file; both must match the manifest."""
    out = []
    for r in manifest.itertuples():
        path = RAW / r.file
        rows_ok = path.suffix != ".csv" or count_csv_rows(path) == int(r.rows)
        out.append({"file": r.file, "rows_match": rows_ok, "hash_match": sha256(path) == r.sha256})
    return pd.DataFrame(out)


def check_volumes(manifest: pd.DataFrame, cfg: dict) -> pd.DataFrame:
    shots = manifest[(manifest.kind == "shots") & (manifest.route == "B_bulk")].copy()
    ranges = cfg["data"]["expected_fga"]

    def in_range(r):
        lo, hi = ranges["playoffs" if r.season_type == "Playoffs" else "regular_season"]
        return lo <= int(r.rows) <= hi

    shots["in_expected_range"] = shots.apply(in_range, axis=1)
    return shots[["season", "season_type", "rows", "in_expected_range"]]


def cross_check(season: str, season_type: str) -> dict:
    """Compare one season between the bulk files and nba_api, shot by shot."""
    code = "po" if season_type == "Playoffs" else "rs"
    bulk_name = f"shotdetail_{'po_' if code == 'po' else ''}{season[:4]}.csv"
    bulk = pd.read_csv(RAW / "bulk" / bulk_name)
    api = pd.read_csv(RAW / "nba_api" / "shots" / f"shotchart_{code}_{season}.csv")
    merged = bulk.merge(api, on=KEY, how="outer", suffixes=("_bulk", "_api"), indicator=True)
    both = merged[merged["_merge"] == "both"]
    compare = ["SHOT_MADE_FLAG", "SHOT_DISTANCE", "LOC_X", "LOC_Y", "SHOT_ZONE_BASIC", "ACTION_TYPE"]
    disagree = {c: int((both[f"{c}_bulk"] != both[f"{c}_api"]).sum()) for c in compare}
    return {
        "season": season, "season_type": season_type,
        "rows_bulk": len(bulk), "rows_api": len(api),
        "only_bulk": int((merged["_merge"] == "left_only").sum()),
        "only_api": int((merged["_merge"] == "right_only").sum()),
        "matched": len(both), **{f"diff_{c}": n for c, n in disagree.items()},
    }


def main() -> int:
    cfg = load_config()
    manifest = pd.read_csv(MANIFEST, dtype={"rows": "Int64"})
    integrity = check_manifest(manifest)
    volumes = check_volumes(manifest, cfg)
    cross = pd.DataFrame([cross_check("2024-25", t) for t in cfg["data"]["season_types"]])

    allstars = pd.read_csv(ROOT / "data" / "reference" / "allstars.csv")
    players = pd.concat(
        [pd.read_csv(p).assign(season=p.stem.split("_")[1])
         for p in sorted((RAW / "nba_api" / "players").glob("playerindex_*.csv"))])

    ok = integrity[["rows_match", "hash_match"]].all().all() and volumes.in_expected_range.all()
    lines = [
        "# Stage 2: data acquisition report",
        "",
        "Generated by `python -m hothand.verify_raw`. Do not edit by hand.",
        "",
        f"**Gate status: {'PASS' if ok else 'FAIL'}**",
        "",
        "## Manifest integrity",
        (f"{len(integrity)} files; rows match manifest: {integrity.rows_match.all()}; "
         f"hashes match: {integrity.hash_match.all()}."),
        "",
        "## Shot volume per season (bulk route)",
        (f"Expected range: regular season {cfg['data']['expected_fga']['regular_season']}, "
         f"playoffs {cfg['data']['expected_fga']['playoffs']}."),
        "",
        volumes.to_markdown(index=False),
        "",
        "## Cross-check: bulk dataset vs nba_api, 2024-25",
        ("Shots matched on game ID, game event ID and player ID; `diff_*` counts matched shots "
         "whose value differs between routes."),
        "",
        cross.set_index(["season", "season_type"]).T.to_markdown(),
        "",
        "## Reference tables",
        (f"- Player index: {players.PERSON_ID.nunique()} distinct players across "
         f"{players.season.nunique()} season files (nba_api `PlayerIndex`)."),
        (f"- All-Stars: {len(allstars)} player-season selections, "
         f"{allstars.groupby('season').size().min()}-{allstars.groupby('season').size().max()} "
         "per season (Wikipedia All-Star Game rosters, revision ids stored)."),
        "",
    ]
    REPORT.write_text("\n".join(lines))
    print("\n".join(lines))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
